#!/usr/bin/env node
// Framework bindings for every component package, generated from its custom-elements.json (run
// `pnpm analyze` first):
//   src/react.ts        React wrappers (@lit/react), the `@lit-material/<pkg>/react` entry   (committed)
//   types/jsx.d.ts      React JSX.IntrinsicElements typings, `@lit-material/<pkg>/jsx`     (committed)
//   types/vue.d.ts      Vue GlobalComponents typings, `@lit-material/<pkg>/vue`             (committed)
//   dist/web-types.json, dist/vscode.html-custom-data.json   editor metadata (built, carries the version)
// and the package.json fields that point at them.
//   node tools/framework-bindings.mjs          write everything
//   node tools/framework-bindings.mjs --check  fail when a committed file or package.json is out of date
import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const check = process.argv.includes("--check");
const HEADER = "// Generated by tools/framework-bindings.mjs from custom-elements.json. Do not edit.";
const EVENT_NAME = /^[a-z][a-z0-9-]*$/;
const stale = [];

const pascal = (kebab) => kebab.replace(/(^|-)([a-z0-9])/g, (_, __, c) => c.toUpperCase());
const handlerProp = (event) => `on${pascal(event)}`;
const oneLine = (text = "") => text.replace(/\s+/g, " ").trim();
const docComment = (text, indent = "") => (text ? `${indent}/** ${oneLine(text).replace(/\*\//g, "*\\/")} */\n` : "");

function elementsOf(manifest) {
  const elements = [];
  for (const mod of manifest.modules ?? []) {
    for (const decl of mod.declarations ?? []) {
      if (!decl.customElement || !decl.tagName) continue;
      const exported = (mod.exports ?? []).some((e) => e.kind === "js" && e.declaration?.name === decl.name);
      if (!exported) continue;
      const fields = (decl.members ?? []).filter(
        (m) =>
          m.kind === "field" &&
          !m.static &&
          !m.readonly &&
          (m.privacy === undefined || m.privacy === "public") &&
          !m.name.startsWith("_") &&
          !m.name.startsWith("#"),
      );
      const events = [];
      for (const e of decl.events ?? []) {
        if (!e.name || !EVENT_NAME.test(e.name) || events.some((x) => x.name === e.name)) continue;
        events.push({ name: e.name, custom: /^CustomEvent\b/.test(e.type?.text ?? ""), description: e.description });
      }
      elements.push({
        tag: decl.tagName,
        className: decl.name,
        module: `./${mod.path.replace(/^src\//, "").replace(/\.ts$/, ".js")}`,
        description: decl.description || decl.summary || "",
        fields: [...new Set(fields.map((f) => f.name))].sort(),
        fieldDocs: Object.fromEntries(fields.map((f) => [f.name, f])),
        attributes: (decl.attributes ?? []).filter((a) => a.name),
        events,
        slots: decl.slots ?? [],
      });
    }
  }
  return elements.sort((a, b) => a.tag.localeCompare(b.tag));
}

function wrapperName(className, taken) {
  let name = className.replace(/^LitMaterial/, "") || className;
  while (taken.has(name)) name = `${name}Element`;
  taken.add(name);
  return name;
}

function reactSource(elements) {
  const taken = new Set();
  const byModule = new Map();
  for (const el of elements) byModule.set(el.module, [...(byModule.get(el.module) ?? []), el.className]);
  const imports = [...byModule].map(([mod, names]) => `import { ${[...new Set(names)].sort().join(", ")} } from "${mod}";`);
  const anyEvents = elements.some((el) => el.events.length > 0);
  const body = elements.map((el) => {
    const name = wrapperName(el.className, taken);
    const events = el.events.map(
      (e) => `    ${handlerProp(e.name)}: "${e.name}" as EventName<${e.custom ? "CustomEvent" : "Event"}>,\n`,
    );
    return (
      `/** React wrapper for \`<${el.tag}>\`. */\n` +
      `export const ${name} = createComponent({\n` +
      `  tagName: "${el.tag}",\n` +
      `  elementClass: ${el.className},\n` +
      `  react: React,\n` +
      (events.length ? `  events: {\n${events.join("")}  },\n` : "") +
      `  displayName: "${name}",\n` +
      `});\n`
    );
  });
  return [
    HEADER,
    `// React 18 and 19 wrappers: properties set as properties, events as \`on<Event>\` props.`,
    `import * as React from "react";`,
    `import { createComponent${anyEvents ? ", type EventName" : ""} } from "@lit/react";`,
    ...imports,
    "",
    body.join("\n"),
  ].join("\n");
}

function typeImports(elements) {
  const byModule = new Map();
  for (const el of elements) byModule.set(el.module, [...(byModule.get(el.module) ?? []), el.className]);
  return [...byModule].map(
    ([mod, names]) => `import type { ${[...new Set(names)].sort().join(", ")} } from "../dist/${mod.slice(2).replace(/\.js$/, ".js")}";`,
  );
}

const fieldUnion = (el) => (el.fields.length ? el.fields.map((f) => `"${f}"`).join(" | ") : "never");

function jsxSource(elements) {
  const entries = elements.map((el) => {
    const handlers = el.events.map(
      (e) => `        ${JSON.stringify(`on${e.name}`)}?: (event: ${e.custom ? "CustomEvent" : "Event"}) => void;\n`,
    );
    return (
      docComment(el.description || `<${el.tag}>`, "      ") +
      `      "${el.tag}": ElementProps<${el.className}, ${fieldUnion(el)}>` +
      (handlers.length ? ` & {\n${handlers.join("")}      }` : "") +
      ";\n"
    );
  });
  return [
    HEADER,
    "// React 19 renders custom elements natively; this types them in JSX. Load it with",
    '// `import type {} from "<package>/jsx";`. React 19 adds a listener for `on<event>` props as written.',
    'import type { DetailedHTMLProps, HTMLAttributes } from "react";',
    ...typeImports(elements),
    "",
    "type ElementProps<E, K extends keyof E> = Omit<DetailedHTMLProps<HTMLAttributes<E>, E>, K> & Partial<Pick<E, K>>;",
    "",
    'declare module "react" {',
    "  namespace JSX {",
    "    interface IntrinsicElements {",
    entries.join("").replace(/\n$/, ""),
    "    }",
    "  }",
    "}",
    "",
  ].join("\n");
}

function vueSource(elements) {
  const entries = elements.map((el) => {
    const handlers = el.events.map(
      (e) => `        ${handlerProp(e.name)}?: (event: ${e.custom ? "CustomEvent" : "Event"}) => void;\n`,
    );
    return (
      docComment(el.description || `<${el.tag}>`, "    ") +
      `    "${el.tag}": DefineComponent<Partial<Pick<${el.className}, ${fieldUnion(el)}>>` +
      (handlers.length ? ` & {\n${handlers.join("")}      }` : "") +
      ">;\n"
    );
  });
  return [
    HEADER,
    "// Types the elements in Vue templates (Volar). Load it with `import type {} from \"<package>/vue\";`, and",
    "// tell the compiler they're custom elements: compilerOptions.isCustomElement = (tag) => tag.startsWith(\"lit-material-\").",
    'import type { DefineComponent } from "vue";',
    ...typeImports(elements),
    "",
    'declare module "vue" {',
    "  interface GlobalComponents {",
    entries.join("").replace(/\n$/, ""),
    "  }",
    "}",
    "",
  ].join("\n");
}

function webTypes(pkg, elements) {
  return {
    $schema: "https://json.schemastore.org/web-types",
    name: pkg.name,
    version: pkg.version,
    "description-markup": "markdown",
    contributions: {
      html: {
        elements: elements.map((el) => ({
          name: el.tag,
          description: oneLine(el.description) || undefined,
          "doc-url": pkg.homepage,
          attributes: el.attributes.map((a) => ({
            name: a.name,
            description: oneLine(a.description) || undefined,
            value: { type: a.type?.text ?? "string" },
          })),
          slots: el.slots.map((s) => ({ name: s.name ?? "", description: oneLine(s.description) || undefined })),
          events: el.events.map((e) => ({ name: e.name, description: oneLine(e.description) || undefined })),
          js: {
            properties: el.fields.map((f) => ({
              name: f,
              description: oneLine(el.fieldDocs[f]?.description) || undefined,
              type: el.fieldDocs[f]?.type?.text,
            })),
            events: el.events.map((e) => ({ name: e.name, description: oneLine(e.description) || undefined })),
          },
        })),
      },
    },
  };
}

function customData(pkg, elements) {
  return {
    $schema: "https://raw.githubusercontent.com/microsoft/vscode-html-languageservice/main/docs/customData.schema.json",
    version: 1.1,
    tags: elements.map((el) => ({
      name: el.tag,
      description: oneLine(el.description) || `\`<${el.tag}>\` from ${pkg.name}`,
      attributes: el.attributes.map((a) => {
        const values = [...(a.type?.text ?? "").matchAll(/"([^"]+)"/g)].map((m) => ({ name: m[1] }));
        return { name: a.name, description: oneLine(a.description) || undefined, values: values.length ? values : undefined };
      }),
      references: pkg.homepage ? [{ name: "Documentation", url: pkg.homepage }] : undefined,
    })),
  };
}

function bindingsFields(pkg) {
  const next = { ...pkg };
  next.exports = {
    ...pkg.exports,
    "./react": { types: "./dist/react.d.ts", default: "./dist/react.js" },
    "./jsx": { types: "./types/jsx.d.ts" },
    "./vue": { types: "./types/vue.d.ts" },
  };
  next.files = [...new Set([...(pkg.files ?? ["dist"]), "types"])];
  next["web-types"] = "./dist/web-types.json";
  next.peerDependencies = { ...pkg.peerDependencies, "@lit/react": "^1.0.0", react: ">=18" };
  next.peerDependenciesMeta = {
    ...pkg.peerDependenciesMeta,
    "@lit/react": { optional: true },
    react: { optional: true },
  };
  // Keep a stable key order: the generated fields go right after "exports"/"files".
  const ordered = {};
  for (const [key, value] of Object.entries(next)) {
    if (["web-types", "peerDependencies", "peerDependenciesMeta"].includes(key)) continue;
    ordered[key] = value;
    if (key === "files") ordered["web-types"] = next["web-types"];
    if (key === "dependencies" || (key === "files" && !next.dependencies)) {
      ordered.peerDependencies = next.peerDependencies;
      ordered.peerDependenciesMeta = next.peerDependenciesMeta;
    }
  }
  for (const key of ["web-types", "peerDependencies", "peerDependenciesMeta"]) if (!(key in ordered)) ordered[key] = next[key];
  return ordered;
}

function put(file, content) {
  const current = existsSync(file) ? readFileSync(file, "utf8") : undefined;
  if (current === content) return;
  if (check) {
    stale.push(file.slice(root.length + 1));
    return;
  }
  mkdirSync(dirname(file), { recursive: true });
  writeFileSync(file, content);
}

let packages = 0;
let elementCount = 0;
for (const dir of readdirSync(join(root, "packages")).sort()) {
  const pkgDir = join(root, "packages", dir);
  const pkgFile = join(pkgDir, "package.json");
  const manifestFile = join(pkgDir, "custom-elements.json");
  if (!existsSync(pkgFile)) continue;
  const pkg = JSON.parse(readFileSync(pkgFile, "utf8"));
  if (pkg.private) continue;
  if (!existsSync(manifestFile)) {
    if (!pkg.scripts?.analyze) continue; // no elements to describe (core, store, tokens, ...)
    console.error(`${pkg.name}: no custom-elements.json — run pnpm analyze first`);
    process.exit(1);
  }
  const elements = elementsOf(JSON.parse(readFileSync(manifestFile, "utf8")));
  if (elements.length === 0) continue;
  packages++;
  elementCount += elements.length;

  put(join(pkgDir, "src", "react.ts"), reactSource(elements));
  put(join(pkgDir, "types", "jsx.d.ts"), jsxSource(elements));
  put(join(pkgDir, "types", "vue.d.ts"), vueSource(elements));
  put(pkgFile, `${JSON.stringify(bindingsFields(pkg), null, 2)}\n`);
  if (!check && existsSync(join(pkgDir, "dist"))) {
    writeFileSync(join(pkgDir, "dist", "web-types.json"), `${JSON.stringify(webTypes(pkg, elements), null, 2)}\n`);
    writeFileSync(
      join(pkgDir, "dist", "vscode.html-custom-data.json"),
      `${JSON.stringify(customData(pkg, elements), null, 2)}\n`,
    );
  }
}

if (stale.length) {
  console.error(`Out of date — run node tools/framework-bindings.mjs and commit:\n  ${stale.join("\n  ")}`);
  process.exit(1);
}
console.log(`${check ? "Checked" : "Wrote"} bindings for ${elementCount} elements in ${packages} packages.`);
