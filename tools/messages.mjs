#!/usr/bin/env node
// The English message catalog, extracted from the components: every `localize.term("key", english, ...)`
// call in packages/*/src (tests excluded), parsed with the TypeScript compiler. Writes
// packages/translations/src/en.ts, the reference every other catalog is checked against.
//   node tools/messages.mjs          write en.ts
//   node tools/messages.mjs --check  fail when en.ts is out of date, a key has two different English texts,
//                                    or the English isn't a literal
import { existsSync, readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const ts = createRequire(join(root, "packages", "core", "package.json"))("typescript");
const check = process.argv.includes("--check");
const target = join(root, "packages", "translations", "src", "en.ts");

function sourceFiles(dir) {
  const out = [];
  for (const name of readdirSync(dir)) {
    const path = join(dir, name);
    if (statSync(path).isDirectory()) out.push(...sourceFiles(path));
    else if (name.endsWith(".ts") && !name.endsWith(".test.ts") && !name.endsWith(".d.ts")) out.push(path);
  }
  return out;
}

function literal(node, where) {
  if (ts.isStringLiteral(node) || ts.isNoSubstitutionTemplateLiteral(node)) return node.text;
  if (ts.isObjectLiteralExpression(node)) {
    const forms = {};
    for (const prop of node.properties) {
      if (!ts.isPropertyAssignment(prop) || !(ts.isStringLiteral(prop.initializer) || ts.isNoSubstitutionTemplateLiteral(prop.initializer))) {
        throw new Error(`${where}: plural forms must be string literals`);
      }
      forms[prop.name.getText().replace(/^["']|["']$/g, "")] = prop.initializer.text;
    }
    if (!("other" in forms)) throw new Error(`${where}: plural forms need "other"`);
    return forms;
  }
  throw new Error(`${where}: the English text must be a string literal or an object of plural forms`);
}

const messages = new Map();
const errors = [];
for (const pkg of readdirSync(join(root, "packages")).sort()) {
  const src = join(root, "packages", pkg, "src");
  if (pkg === "translations" || !existsSync(src)) continue;
  for (const file of sourceFiles(src)) {
    const text = readFileSync(file, "utf8");
    if (!text.includes(".term(")) continue;
    const source = ts.createSourceFile(file, text, ts.ScriptTarget.Latest, true);
    const visit = (node) => {
      if (
        ts.isCallExpression(node) &&
        ts.isPropertyAccessExpression(node.expression) &&
        node.expression.name.text === "term" &&
        node.arguments.length >= 2
      ) {
        const { line } = source.getLineAndCharacterOfPosition(node.getStart());
        const where = `${relative(root, file)}:${line + 1}`;
        const [keyNode, englishNode] = node.arguments;
        try {
          if (!ts.isStringLiteral(keyNode)) throw new Error(`${where}: the key must be a string literal`);
          const key = keyNode.text;
          if (!/^[a-z][A-Za-z0-9]*\.[a-z][A-Za-z0-9]*$/.test(key)) throw new Error(`${where}: key "${key}" isn't <package>.<message>`);
          const english = literal(englishNode, where);
          const seen = messages.get(key);
          if (seen && JSON.stringify(seen.english) !== JSON.stringify(english)) {
            throw new Error(`${where}: "${key}" has different English at ${seen.where}`);
          }
          if (!seen) messages.set(key, { english, where });
        } catch (error) {
          errors.push(error.message);
        }
      }
      ts.forEachChild(node, visit);
    };
    visit(source);
  }
}
if (errors.length) {
  console.error(errors.join("\n"));
  process.exit(1);
}

const keys = [...messages.keys()].sort();
const lines = keys.map((key) => {
  const { english } = messages.get(key);
  const value =
    typeof english === "string"
      ? JSON.stringify(english)
      : `{ ${Object.entries(english).map(([form, text]) => `${form}: ${JSON.stringify(text)}`).join(", ")} }`;
  return `  ${JSON.stringify(key)}: ${value},`;
});
const output = `// Generated by tools/messages.mjs from the components' own English. Do not edit: change the
// component, then run \`node tools/messages.mjs\`. Every other catalog is checked against these keys.
import type { Translation } from "@lit-material/core/localize.js";

const en = {
  $code: "en",
  $name: "English",
  $dir: "ltr",
${lines.join("\n")}
} satisfies Translation;

export default en;

/** Every message key the components use. */
export type MessageKey = Exclude<keyof typeof en, \`$\${string}\`>;
`;

const current = existsSync(target) ? readFileSync(target, "utf8") : "";
if (current !== output) {
  if (check) {
    console.error("packages/translations/src/en.ts is out of date — run node tools/messages.mjs and commit.");
    process.exit(1);
  }
  writeFileSync(target, output);
}
console.log(`${check ? "Checked" : "Wrote"} ${keys.length} messages.`);
