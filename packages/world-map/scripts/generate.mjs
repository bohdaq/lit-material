#!/usr/bin/env node
// Country shapes for <lit-material-world-map> (src/countries.ts).
//   node scripts/generate.mjs              fetch Natural Earth at the pinned commit and regenerate
//   node scripts/generate.mjs --from FILE  regenerate from a downloaded ne_110m_admin_0_countries.geojson
//   node scripts/generate.mjs --check      fail when src/countries.ts isn't well formed (offline)
//
// Source: Natural Earth 1:110m Admin 0 – Countries (public domain, https://www.naturalearthdata.com), from
// github.com/nvkelso/natural-earth-vector at COMMIT. Countries are keyed by ISO_A2_EH (ISO 3166-1 alpha-2,
// with France, Norway and Kosovo filled in); Antarctica and features without a code are left out. Equal Earth
// projection, viewBox 0 0 1000 H, coordinates rounded to whole units with repeated points dropped, outer rings
// only, written as relative path commands: one SVG path per country.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const OUTPUT = join(dirname(fileURLToPath(import.meta.url)), "..", "src", "countries.ts");
const COMMIT = "ca96624a56bd078437bca8184e78163e5039ad19";
const URL = `https://raw.githubusercontent.com/nvkelso/natural-earth-vector/${COMMIT}/geojson/ne_110m_admin_0_countries.geojson`;
const WIDTH = 1000;
const SOUTH = -58; // crop below Tierra del Fuego (no Antarctica)

const [A1, A2, A3, A4] = [1.340264, -0.081106, 0.000893, 0.003796];
const M = Math.sqrt(3) / 2;
const rad = (d) => (d * Math.PI) / 180;

function equalEarth(lon, lat) {
  const lam = rad(lon);
  const t = Math.asin(M * Math.sin(rad(lat)));
  const t2 = t * t;
  const t6 = t2 ** 3;
  const x = (lam * Math.cos(t)) / (M * (A1 + 3 * A2 * t2 + t6 * (7 * A3 + 9 * A4 * t2)));
  const y = t * (A1 + A2 * t2 + t6 * (A3 + A4 * t2));
  return [x, y];
}

const XMAX = equalEarth(180, 0)[0];
const YTOP = equalEarth(0, 90)[1];
const YBOTTOM = equalEarth(0, SOUTH)[1];
const SCALE = WIDTH / (2 * XMAX);
const HEIGHT = Math.round((YTOP - YBOTTOM) * SCALE);

function point(lon, lat) {
  const [x, y] = equalEarth(lon, Math.max(lat, SOUTH));
  return [Math.round((x + XMAX) * SCALE), Math.round((YTOP - y) * SCALE)];
}

// "M x y" then relative steps; a minus sign separates numbers on its own.
const pair = (dx, dy) => `${dx}${dy < 0 ? "" : " "}${dy}`;

function ringPath(ring) {
  const pts = [];
  for (const [lon, lat] of ring) {
    const p = point(lon, lat);
    const last = pts.at(-1);
    if (!last || last[0] !== p[0] || last[1] !== p[1]) pts.push(p);
  }
  if (pts.length < 3) return "";
  const steps = [];
  for (let i = 1; i < pts.length; i++) steps.push(pair(pts[i][0] - pts[i - 1][0], pts[i][1] - pts[i - 1][1]));
  return `M${pts[0][0]} ${pts[0][1]}l${steps.join(" ").replace(/ -/g, "-")}z`;
}

function build(geojson) {
  const countries = {};
  for (const f of geojson.features) {
    const props = f.properties;
    const code = String(props.ISO_A2_EH ?? props.ISO_A2 ?? "").toUpperCase();
    if (!/^[A-Z]{2}$/.test(code) || code === "AQ") continue;
    const g = f.geometry;
    const polys = g.type === "MultiPolygon" ? g.coordinates : [g.coordinates];
    const d = polys.map((poly) => ringPath(poly[0])).join("");
    if (d) countries[code] = (countries[code] ?? "") + d;
  }
  const lines = [
    "// Generated by scripts/generate.mjs from Natural Earth 1:110m countries",
    `// (public domain, nvkelso/natural-earth-vector@${COMMIT.slice(0, 12)}) — don't edit.`,
    "",
    "/** The map's coordinate space: Equal Earth, 1000 units wide, cropped at 58°S. */",
    `export const VIEWBOX = "0 0 ${WIDTH} ${HEIGHT}";`,
    "",
    "/** One SVG path per country, keyed by ISO 3166-1 alpha-2 code. */",
    "export const COUNTRIES: Readonly<Record<string, string>> = {",
    ...Object.keys(countries)
      .sort()
      .map((code) => `  ${code}: "${countries[code]}",`),
    "};",
    "",
  ];
  return lines.join("\n");
}

function check() {
  const text = readFileSync(OUTPUT, "utf8");
  const n = [...text.matchAll(/^ {2}[A-Z]{2}: "M[-0-9 lMz]+",$/gm)].length;
  if (n < 150 || !text.includes("export const VIEWBOX")) {
    console.error(`${OUTPUT}: malformed (${n} countries)`);
    process.exit(1);
  }
  console.log(`${OUTPUT}: ${n} countries, ${text.length} bytes`);
}

const args = process.argv.slice(2);
if (args[0] === "--check") {
  check();
} else {
  const data =
    args[0] === "--from" && args[1]
      ? JSON.parse(readFileSync(args[1], "utf8"))
      : await (await fetch(URL, { headers: { "User-Agent": "lit-material world-map generator" } })).json();
  writeFileSync(OUTPUT, build(data));
  check();
}
