#!/usr/bin/env node
// Writes src/generated.ts: facts about lit-material read from the repository, which the codemod's warnings
// and the mapping tests use.
//   - every lit-material element: its package, attributes, CSS custom properties and CSS parts (from each
//     package's custom-elements.json, so run `pnpm analyze` first);
//   - every --md-sys-* token a lit-material package defines or reads.
// `node scripts/generate.mjs --check` exits 1 when src/generated.ts is out of date (the tests run it too).
import { existsSync, readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const packages = join(here, "..", "..");
const out = join(here, "..", "src", "generated.ts");

export function generate() {
  const elements = {};
  const tokens = new Set();
  for (const dir of readdirSync(packages).sort()) {
    if (dir === "codemod") continue;
    const pkgFile = join(packages, dir, "package.json");
    if (!existsSync(pkgFile)) continue;
    const pkg = JSON.parse(readFileSync(pkgFile, "utf8"));
    const cem = join(packages, dir, "custom-elements.json");
    const aliases = new Map();
    if (existsSync(join(packages, dir, "src"))) walk(join(packages, dir, "src"), (file) => {
      if (!file.endsWith(".ts") || file.endsWith(".test.ts")) return;
      for (const m of readFileSync(file, "utf8").matchAll(/export type (\w+) =\s*([^;]+);/g)) aliases.set(m[1], m[2].replace(/\s+/g, " ").trim());
    });
    if (existsSync(cem)) {
      for (const mod of JSON.parse(readFileSync(cem, "utf8")).modules ?? []) {
        for (const d of mod.declarations ?? []) {
          if (!d.tagName || !d.tagName.startsWith("lit-material-")) continue;
          elements[d.tagName] = {
            package: pkg.name,
            className: d.name,
            attributes: Object.fromEntries(
              (d.attributes ?? []).map((a) => [a.name, expand(a.type?.text ?? "", aliases)]).sort(([a], [b]) => a.localeCompare(b)),
            ),
            events: [...new Set((d.events ?? []).map((e) => e.name).filter(Boolean))].sort(),
            slots: [...new Set((d.slots ?? []).map((s) => s.name))].sort(),
            cssProperties: [...new Set((d.cssProperties ?? []).map((p) => p.name))].sort(),
            cssParts: [...new Set((d.cssParts ?? []).map((p) => p.name))].sort(),
          };
        }
      }
    }
    const src = join(packages, dir, "src");
    if (existsSync(src)) walk(src, (file) => {
      if (!/\.(ts|css)$/.test(file) || /\.test\.ts$/.test(file)) return;
      for (const m of readFileSync(file, "utf8").matchAll(/--md-sys-[a-z0-9-]*[a-z0-9]/g)) tokens.add(m[0]);
    });
  }
  const sorted = Object.fromEntries(Object.entries(elements).sort(([a], [b]) => a.localeCompare(b)));
  return `// Generated by scripts/generate.mjs from the lit-material packages' custom-elements.json and sources. Don't edit.

export interface LitElementFacts {
  package: string;
  className: string;
  /** Attribute name → its type, with string-literal aliases spelled out. */
  attributes: Record<string, string>;
  events: string[];
  slots: string[];
  cssProperties: string[];
  cssParts: string[];
}

export const LIT_ELEMENTS: Record<string, LitElementFacts> = ${JSON.stringify(sorted, null, 2)};

/** Every --md-sys-* token a lit-material package defines or reads. */
export const SYS_TOKENS: readonly string[] = ${JSON.stringify([...tokens].sort(), null, 2)};
`;
}

/** A type alias of string literals spelled out (`ButtonVariant` → `"filled" | "outlined" | …`). */
function expand(type, aliases) {
  return type.replace(/\b[A-Z]\w*\b/g, (name) => (aliases.has(name) && /^("[^"]*"\s*\|?\s*)+$/.test(aliases.get(name)) ? aliases.get(name) : name));
}

function walk(dir, fn) {
  for (const name of readdirSync(dir)) {
    const p = join(dir, name);
    if (statSync(p).isDirectory()) walk(p, fn);
    else fn(p);
  }
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const next = generate();
  if (process.argv.includes("--check")) {
    const current = existsSync(out) ? readFileSync(out, "utf8") : "";
    if (current !== next) {
      console.error("src/generated.ts is out of date: run node scripts/generate.mjs (after pnpm analyze).");
      process.exit(1);
    }
  } else {
    writeFileSync(out, next);
    console.log(`Wrote ${out}`);
  }
}
